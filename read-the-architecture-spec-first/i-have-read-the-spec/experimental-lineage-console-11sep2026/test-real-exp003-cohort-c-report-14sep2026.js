'use strict';
const fs=require('fs');
const assert=require('assert');
const {run}=require('./exp003-cohort-c-report-14sep2026.js');
const indexPath=process.argv[2];
if (!indexPath) throw new Error('index_path_required');
const index=JSON.parse(fs.readFileSync(indexPath,'utf8'));
const result=run(index);
assert.equal(result.itemCount,25);
assert.equal(result.observationCount,250);
assert(result.summaries.every(s=>s.observationCount===10));
assert(result.summaries.every(s=>s.replicateCount===10));
assert(result.summaries.every(s=>s.missingCount===0));
const byId=Object.fromEntries(result.summaries.map(s=>[s.itemId,s]));
assert.deepEqual(byId.A1.sentinelCounts,{NEVER:3,ALWAYS:3});
assert.deepEqual(byId.B02.sentinelCounts,{ALWAYS:9});
assert.equal(byId.I1.categoricalCount,10);
assert.equal(byId.I1.numericCount,0);
console.log(JSON.stringify({status:'PASS',items:result.itemCount,observations:result.observationCount,missing:result.summaries.reduce((a,s)=>a+s.missingCount,0)}));
